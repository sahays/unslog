#[derive(Clone)]
pub struct OpenRouter {
    http: reqwest::Client,
    api_key: String,
    /// Optional value to send as `HTTP-Referer`. `None` = omit the header
    /// (default). Set via `AppConfig::referer` / `UNSLOG_REFERER`.
    referer: Option<String>,
}

impl OpenRouter {
    pub fn new(http: reqwest::Client, api_key: String, referer: Option<String>) -> Self {
        Self {
            http,
            api_key,
            referer,
        }
    }

    pub fn configured(&self) -> bool {
        !self.api_key.trim().is_empty()
    }

    fn require_key(&self) -> Result<&str, AppError> {
        if self.api_key.trim().is_empty() {
            Err(AppError::OpenRouterNotConfigured)
        } else {
            Ok(&self.api_key)
        }
    }

    /// Attach the standard attribution headers OpenRouter expects.
    /// `HTTP-Referer` is only sent when [`AppConfig::referer`] is configured,
    /// so the default install doesn't leak a hard-coded personal repo URL.
    fn with_attribution(&self, mut req: reqwest::RequestBuilder) -> reqwest::RequestBuilder {
        if let Some(referer) = self.referer.as_deref() {
            req = req.header("HTTP-Referer", referer);
        }
        req.header("X-Title", "unslog")
    }

    /// Common headers — bearer + (optional) referer + title.
    pub(crate) fn auth_get(&self, url: &str) -> Result<reqwest::RequestBuilder, AppError> {
        let key = self.require_key()?;
        Ok(self.with_attribution(self.http.get(url).bearer_auth(key)))
    }

    pub(crate) fn auth_post(&self, url: &str) -> Result<reqwest::RequestBuilder, AppError> {
        let key = self.require_key()?;
        Ok(self.with_attribution(self.http.post(url).bearer_auth(key)))
    }

    // list_models_raw lives in list_models.rs.
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatMessage {
    pub role: String,
    pub content: String,
}

impl ChatMessage {
    pub fn system(content: impl Into<String>) -> Self {
        Self {
            role: "system".into(),
            content: content.into(),
        }
    }
    pub fn user(content: impl Into<String>) -> Self {
        Self {
            role: "user".into(),
            content: content.into(),
        }
    }
}

/// Chat-completion response shape used by `chat`, `chat_with_web_search`,
/// and `stt` (since STT goes via the chat-completions endpoint with an
/// `input_audio` content block).
#[derive(Debug, Deserialize)]
pub(crate) struct ChatCompletion {
    pub(crate) choices: Vec<ChatChoice>,
}

#[derive(Debug, Deserialize)]
pub(crate) struct ChatChoice {
    pub(crate) message: ChatChoiceMessage,
}

#[derive(Debug, Deserialize)]
pub(crate) struct ChatChoiceMessage {
    pub(crate) content: String,
    /// Present when OpenRouter ran a plugin (e.g. web search). Each entry
    /// records a URL the plugin fetched. Absent in plain chat responses.
    #[serde(default)]
    pub(crate) annotations: Vec<chat::Annotation>,
}

