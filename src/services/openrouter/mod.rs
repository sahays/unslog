/// Errors we'll retry once. Transient classifier shared by every
/// retry_once-wrapped call. Reqwest body-decode + upstream-error responses
/// are the two flakes we've observed on OpenRouter — anything else
/// (`BadRequest`, `OpenRouterNotConfigured`, `Mongo`, etc.) is deterministic
/// and a retry would just burn tokens.
pub(crate) fn is_transient(e: &AppError) -> bool {
    matches!(e, AppError::Http(_) | AppError::Upstream(_))
}

/// Invoke `f`, retry once on transient errors. Used by every outbound
/// OpenRouter call (chat / chat_web / tts / stt) — the chat/audio APIs
/// occasionally return mid-stream body-decode errors, and the cheapest
/// available mitigation is one fresh attempt.
pub(crate) async fn retry_once<T, F, Fut>(op: &'static str, mut f: F) -> Result<T, AppError>
where
    F: FnMut() -> Fut,
    Fut: Future<Output = Result<T, AppError>>,
{
    match f().await {
        Ok(v) => Ok(v),
        Err(first) => {
            if !is_transient(&first) {
                return Err(first);
            }
            // The full Display of `Upstream` includes the upstream status;
            // bound it with `preview` so a future variant that ends up
            // wrapping a large body can't flood the log line.
            let first_str = first.to_string();
            tracing::warn!(
                op = %op,
                error_preview = %crate::services::redact::preview(&first_str, 240),
                "first attempt failed, retrying once",
            );
            f().await
        }
    }
}

/// Object-safe abstraction over the four OpenRouter call shapes.
///
/// Production code holds an `Arc<dyn LlmClient>` on `AppState` (built around
/// the real `OpenRouter` struct). Tests inject a `MockLlmClient` generated by
/// `mockall::automock` to pin chat / stt / tts responses without network I/O.
#[cfg_attr(test, mockall::automock)]
#[async_trait]
pub trait LlmClient: Send + Sync {
    async fn chat(
        &self,
        model: &str,
        messages: Vec<ChatMessage>,
        force_json: bool,
    ) -> Result<String, AppError>;

    /// Like [`chat`], but enables OpenRouter's `web` plugin and returns the URLs
    /// the plugin actually fetched (parsed from `message.annotations`) so callers
    /// can distinguish ground-truth citations from anything the model claims in
    /// its body. Empty `fetched_urls` ⇒ search didn't run.
    async fn chat_with_web_search(
        &self,
        model: &str,
        messages: Vec<ChatMessage>,
        force_json: bool,
    ) -> Result<ChatWithWebSearchOut, AppError>;

    async fn stt(&self, model: &str, audio_bytes: &[u8], format: &str) -> Result<String, AppError>;

    async fn tts(
        &self,
        model: &str,
        voice: &str,
        text: &str,
        speed: Option<f32>,
        instructions: &str,
    ) -> Result<bytes::Bytes, AppError>;

    async fn list_models_raw(&self) -> Result<serde_json::Value, AppError>;

    /// Whether an API key is configured. Used by the settings pages to tell
    /// the user whether OpenRouter calls will succeed without exposing the key.
    fn configured(&self) -> bool;
}

#[async_trait]
impl LlmClient for OpenRouter {
    async fn chat(
        &self,
        model: &str,
        messages: Vec<ChatMessage>,
        force_json: bool,
    ) -> Result<String, AppError> {
        OpenRouter::chat(self, model, messages, force_json).await
    }

    async fn chat_with_web_search(
        &self,
        model: &str,
        messages: Vec<ChatMessage>,
        force_json: bool,
    ) -> Result<ChatWithWebSearchOut, AppError> {
        OpenRouter::chat_with_web_search(self, model, messages, force_json).await
    }

    async fn stt(&self, model: &str, audio_bytes: &[u8], format: &str) -> Result<String, AppError> {
        OpenRouter::stt(self, model, audio_bytes, format).await
    }

    async fn tts(
        &self,
        model: &str,
        voice: &str,
        text: &str,
        speed: Option<f32>,
        instructions: &str,
    ) -> Result<bytes::Bytes, AppError> {
        OpenRouter::tts(self, model, voice, text, speed, instructions).await
    }

    async fn list_models_raw(&self) -> Result<serde_json::Value, AppError> {
        OpenRouter::list_models_raw(self).await
    }

    fn configured(&self) -> bool {
        OpenRouter::configured(self)
    }
}

