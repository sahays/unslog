//! Thin OpenRouter client. One client, four shapes of call:
//! 1. Chat completion (text in, text out) — used for critique, summary
//! 2. Chat completion with web tools — used for research agent (model:online)
//! 3. Audio in (base64 input_audio) — used for STT
//! 4. /audio/speech — used for TTS
//!
//! All four go through `reqwest::Client` with the OPENROUTER_API_KEY bearer.

use std::time::Instant;

use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use serde_json::Value;

use crate::error::AppError;

/// Object-safe abstraction over the four OpenRouter call shapes.
///
/// Production code holds an `Arc<dyn LlmClient>` on `AppState` (built around
/// the real `OpenRouter` struct). Tests inject a `MockLlmClient` generated by
/// `mockall::automock` to pin chat / stt / tts responses without network I/O.
#[cfg_attr(test, mockall::automock)]
#[async_trait]
pub trait LlmClient: Send + Sync {
    async fn chat(
        &self,
        model: &str,
        messages: Vec<ChatMessage>,
        force_json: bool,
    ) -> Result<String, AppError>;

    async fn stt(&self, model: &str, audio_bytes: &[u8], format: &str) -> Result<String, AppError>;

    async fn tts(
        &self,
        model: &str,
        voice: &str,
        text: &str,
        speed: Option<f32>,
    ) -> Result<bytes::Bytes, AppError>;

    async fn list_models_raw(&self) -> Result<serde_json::Value, AppError>;

    /// Whether an API key is configured. Used by the settings pages to tell
    /// the user whether OpenRouter calls will succeed without exposing the key.
    fn configured(&self) -> bool;
}

#[async_trait]
impl LlmClient for OpenRouter {
    async fn chat(
        &self,
        model: &str,
        messages: Vec<ChatMessage>,
        force_json: bool,
    ) -> Result<String, AppError> {
        OpenRouter::chat(self, model, messages, force_json).await
    }

    async fn stt(&self, model: &str, audio_bytes: &[u8], format: &str) -> Result<String, AppError> {
        OpenRouter::stt(self, model, audio_bytes, format).await
    }

    async fn tts(
        &self,
        model: &str,
        voice: &str,
        text: &str,
        speed: Option<f32>,
    ) -> Result<bytes::Bytes, AppError> {
        OpenRouter::tts(self, model, voice, text, speed).await
    }

    async fn list_models_raw(&self) -> Result<serde_json::Value, AppError> {
        OpenRouter::list_models_raw(self).await
    }

    fn configured(&self) -> bool {
        OpenRouter::configured(self)
    }
}

